# -*- coding: utf-8 -*-
"""Hand-drawn stone wall tile for style C.

The retail plate's wall is irregular — crooked courses, joints of different
lengths, mortar that wanders.  Cropping that artwork gives stones far too big for
a 320x240 panel (one stone covered a third of the screen) and its seams never
tile.  So the wall is drawn instead: staggered courses with jittered mortar, which
both scales to the panel and repeats without a seam.

  out: main/dg_brick.h (192x192 ARGB8888), docs/opt_brick_tile_preview.png,
       docs/opt_stone_preview.png (tiled over a 320x240 shell)
"""
import math
import os
import random
from PIL import Image, ImageDraw

MAIN = os.path.join('firmware', 'digimon-passport', 'main')
OUT = 128                      # 192 -> 128: ~82 KB less flash (todo #12)
ROWS = 3                       # middle ground: 2 was too sparse, 4 too busy; one joint per course
MORTAR = (128, 128, 128)       # grey; R=G=B so ARGB8888 byte order is moot
ALPHA = 250
rng = random.Random(20261108)  # deterministic: regenerating must not churn the diff

img = Image.new('RGBA', (OUT, OUT), (0, 0, 0, 0))
d = ImageDraw.Draw(img)
course = OUT / ROWS            # 42.67 at 128/3: fractional courses keep the tile seamless


def jitter(x0, y0, x1, y1, steps=6, amp=1, fixed=False):
    """A hand-drawn line: straight between jittered points.

    fixed=True pins the two end points so neighbouring tiles still meet cleanly;
    only the middle wanders (and wanders further than the endpoints would).
    """
    pts = []
    for i in range(steps + 1):
        t = i / steps
        if fixed and (i == 0 or i == steps):
            pts.append((int(x0 + (x1 - x0) * t), int(y0 + (y1 - y0) * t)))
        else:
            pts.append((int(x0 + (x1 - x0) * t + rng.uniform(-amp, amp)),
                        int(y0 + (y1 - y0) * t + rng.uniform(-amp * 1.5, amp * 1.5))))
    return pts


# The course that lands on y=0 / y=128 is the one the eye picks out on a 320x240
# panel: it is the only course drawn twice per tile and clipped by both canvas
# edges, so it used to come out 3 px wide and dead straight while every other
# course wobbled at 5 px.  It now gets a fixed shape with real humps (user pick
# "A", 2026-11-09) and is painted at y and y+OUT, so the half that leaves the top
# of the tile reappears at the bottom and the course stays seamless.
EDGE_COURSE = [(0, 0), (16, 0), (32, -2), (48, -3), (66, -1),
               (84, 0), (100, 1), (116, 0), (OUT, 0)]


def stroke(draw, pts, width=5, fill=MORTAR + (ALPHA,)):
    """Paint a continuous rounded stroke along a polyline.

    ImageDraw.line() at this width leaves 1-2 px holes on a shallow slope (no
    anti-aliasing, integer coordinates), which reads as a broken mortar joint
    once the tile is repeated.  Walking the path in half-pixel steps and
    stamping a disc keeps it continuous.
    """
    r = width / 2.0 - 0.5
    for i in range(len(pts) - 1):
        x0, y0 = pts[i]
        x1, y1 = pts[i + 1]
        n = max(1, int(math.hypot(x1 - x0, y1 - y0) * 2))
        for s in range(n + 1):
            t = s / n
            cx, cy = x0 + (x1 - x0) * t, y0 + (y1 - y0) * t
            draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=fill)


# horizontal courses (including the wrap rows so the tile is seamless)
for r in range(ROWS):
    y = int(round(r * course))
    # Keep the call even for the edge course: dropping it would reshuffle the
    # rng and change every other course and joint in the tile.
    pts = jitter(0, y, OUT, y, steps=10, amp=4, fixed=True)
    if r == 0:
        for off in (0, OUT):
            stroke(d, [(x, yy + off) for x, yy in EDGE_COURSE])
    else:
        d.line(pts, fill=MORTAR + (ALPHA,), width=5)
    # a short crack running into the course here and there
    if rng.random() < 0.5:
        cx = rng.randrange(20, OUT - 20)
        d.line(jitter(cx, y, cx + rng.randrange(-8, 9), y + int(course / 2) - 3, steps=3, amp=2),
               fill=MORTAR + (ALPHA - 25,), width=2)

# vertical joints: one per course, staggered by half a tile, so the stones are
# roughly a whole tile wide instead of a busy grid of small blocks
for r in range(ROWS):
    y0 = int(round(r * course))
    y1 = int(round((r + 1) * course))
    x = (r * (OUT // ROWS) + rng.randrange(-8, 9)) % OUT
    x2 = x + rng.uniform(-6, 6)
    d.line(jitter(x, y0 + 2, x2, y1 - 2, steps=7, amp=4, fixed=True),
           fill=MORTAR + (ALPHA,), width=5)

img.save('docs/opt_brick_tile_preview.png')

raw = []
kept = 0
px = img.load()
for y in range(OUT):
    for x in range(OUT):
        r, g, b, a = px[x, y]
        if a:
            kept += 1
        # A8: the tile only ever carries "mortar or nothing", so one alpha byte
        # per pixel replaces four.  The colour comes from
        # lv_obj_set_style_bg_image_recolor() at runtime (see apply_shell).
        raw.append(a)

L = []
L.append('/* dg_brick.h -- 128x128 A8 stone-wall tile for LVGL bg_image_tiled().')
L.append(' *')
L.append(' * Generated by tools/gen_brick_tile.py.  Irregular staggered courses with')
L.append(' * jittered mortar, drawn rather than cropped: the retail artwork\'s stones are')
L.append(' * far too large for a 320x240 panel and its seams do not tile.  The tile is a')
L.append(' * pure alpha mask (mortar 250, glass 0) recoloured to mid grey at runtime, so')
L.append(' * the shell colour picked in the menu still shows through and every colourway')
L.append(' * gets the same wall.  128x128x1 = 16 KB of flash (ARGB8888 was 64 KB). */')
L.append('#ifndef DG_BRICK_H_INCLUDED')
L.append('#define DG_BRICK_H_INCLUDED')
L.append('')
L.append('#include <stdint.h>')
L.append('#include "lvgl.h"')
L.append('')
L.append('#define DG_BRICK_W %d' % OUT)
L.append('#define DG_BRICK_H %d' % OUT)
L.append('')
L.append('/* Recolour applied by apply_shell(): the A8 mask is pure mortar alpha. */')
L.append('#define DG_BRICK_INK 0x%02X%02X%02X' % (MORTAR[0], MORTAR[1], MORTAR[2]))
L.append('')
L.append('static const uint8_t dg_brick_px[%d] = {' % len(raw))
for i in range(0, len(raw), 16):
    L.append('    ' + ', '.join('0x%02X' % v for v in raw[i:i + 16]) + ',')
L.append('};')
L.append('')
L.append('static const lv_image_dsc_t dg_brick = {')
L.append('    .header.magic = LV_IMAGE_HEADER_MAGIC,')
L.append('    .header.cf = LV_COLOR_FORMAT_A8,')
L.append('    .header.w = DG_BRICK_W,')
L.append('    .header.h = DG_BRICK_H,')
L.append('    .data_size = sizeof(dg_brick_px),')
L.append('    .data = dg_brick_px,')
L.append('};')
L.append('')
L.append('#endif /* DG_BRICK_H_INCLUDED */')
open(os.path.join(MAIN, 'dg_brick.h'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')

demo = Image.new('RGB', (320, 240), (200, 165, 40))
for y in range(0, 240, OUT):
    for x in range(0, 320, OUT):
        demo.paste(img, (x, y), img)
demo.save('docs/opt_stone_preview.png')
print('tile', OUT, 'x', OUT, 'mortar px', kept, 'bytes', len(raw))
