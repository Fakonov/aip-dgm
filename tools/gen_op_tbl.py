# -*- coding: utf-8 -*-
"""Extract the 4096-entry opcode dispatch table from ref/cores/E0C6200.py
and emit a C array of function pointers (dg_op_*)."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "ref", "cores", "E0C6200.py")

text = open(SRC, "r", encoding="utf-8").read()
lines = text.splitlines()

# locate "self._execute = (" and match the closing paren
start = None
for i, ln in enumerate(lines):
    if "self._execute = (" in ln:
        start = i
        break
if start is None:
    raise SystemExit("table start not found")

depth = 0
end = None
for j in range(start, len(lines)):
    ln = lines[j]
    depth += ln.count("(") - ln.count(")")
    if depth == 0:
        end = j
        break
if end is None:
    raise SystemExit("table end not found")

block = "\n".join(lines[start:end + 1])
block = re.sub(r"E0C6200\.(\w+)", r"'\1'", block)
tbl = eval(block.split("=", 1)[1].strip(), {"__builtins__": {}})

if len(tbl) != 4096:
    raise SystemExit("bad table length: %d" % len(tbl))

names = []
for n in tbl:
    if n not in names:
        names.append(n)

# emit C initialiser, 8 per line
rows = []
per = 8
for i in range(0, 4096, per):
    chunk = ", ".join("dg_op_" + n.lstrip("_") for n in tbl[i:i + per])
    rows.append("    /* 0x%03X */ %s," % (i, chunk))
body = "\n".join(rows)

out = []
out.append("/* ---- generated by tools/gen_op_tbl.py from ref/cores/E0C6200.py ---- */")
out.append("static int (*const dg_op_tbl[4096])(dg_cpu *c, uint16_t op) = {")
out.append(body)
out.append("};")
out.append("")
open(os.path.join(HERE, "op_tbl.inc"), "w", encoding="utf-8").write("\n".join(out))

# also a per-index handler-name list for cross-checks
open(os.path.join(HERE, "op_tbl_indices.txt"), "w", encoding="utf-8").write(
    "\n".join("%d %s" % (i, tbl[i]) for i in range(4096)))

sys.stdout.write("table ok: 4096 entries, %d distinct handlers\n" % len(names))
sys.stdout.write("handlers: " + " ".join(names) + "\n")
# run-length summary
prev = tbl[0]
cnt = 1
runs = []
for n in tbl[1:]:
    if n == prev:
        cnt += 1
    else:
        runs.append((prev, cnt))
        prev = n
        cnt = 1
runs.append((prev, cnt))
sys.stdout.write("runs: %d, total %d\n" % (len(runs), sum(c for _, c in runs)))
