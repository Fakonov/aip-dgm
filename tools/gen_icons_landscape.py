"""Bake digimon_icons.h — the eight function-band sprites, one per slot.

    python tools/gen_icons_landscape.py

Layout comes from the measurement in ref/vpet_v1v2v3/屏幕版式说明.md:

  * the icon band is part of the LCD glass, 4 dot-rows tall, 32 columns wide;
  * each icon owns an 8-column slot (4 slots per band), ink centred at ~60 %
    of the slot width, blank glass on both sides;
  * so a sprite is slot-sized: DG_SLOT_W x DG_SLOT_H pixels, background = the
    glass base colour (NOT the shell colour - the shell can change, the glass
    cannot, and baked-in background is what keeps the band seamless).

    off : the artwork in ink olive, no plate
    on  : the same artwork in white on a small rounded plate

A solid silhouette was tried in round 49 and turned the gauge and the band-aid
into black blobs; the lit state keeps the original line art.  The look itself
lives in tools/icon_style.py, shared with tools/mock_v4.py.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import icon_style as S  # noqa: E402

OUT = r"<home>\digimon-passport\firmware\digimon-passport\main\core\digimon_icons.h"

# slot geometry (panel pixels): 8 columns x 4 dot-rows at pitch 7
# pitch 7 -> 224 x 203 glass, 56 px slots; pitch 8 would need a 118 KB canvas
# and the largest free block after LVGL init is 112 KB, so 7 it is.
SLOT_W, SLOT_H = 56, 28
INK_W = int(SLOT_W * 0.60)          # 33 px, the measured 60 % ink rule
INK_H = SLOT_H - 6                  # 22 px, keeps 3 px of glass top and bottom
GLASS = S.GLASS                     # band background == glass base

HEADER = """/* digimon_icons.h - the eight function-band sprites.
 *
 * One sprite per slot: %(w)d x %(h)d RGB565, background = glass base %(glass)s,
 * which is what makes the icon band tile seamlessly into the LCD glass.
 *   outline : %(ink)s artwork, no plate      (unlit segment)
 *   filled  : plate %(plate)s + %(glyph)s    (lit segment)
 * Artwork is bbox-fitted into a %(iw)d x %(ih)d box (60 %% of the slot width,
 * measured from the real glass) and centred, so the wide gauge fills the slot
 * and the narrow bolt does not get blown up to match it.
 *
 * Generated by tools/gen_icons_landscape.py - do not edit. */
#pragma once
#include <stdint.h>

#define DG_SLOT_W %(w)d
#define DG_SLOT_H %(h)d

""" % dict(w=SLOT_W, h=SLOT_H, glass="#%02X%02X%02X" % GLASS,
           ink="#%02X%02X%02X" % S.INK, plate="#%02X%02X%02X" % S.PLATE,
           glyph="#%02X%02X%02X" % S.GLYPH, iw=INK_W, ih=INK_H)


def emit(fh, name, kind, img):
    fh.write("/* %s %s */\n" % (name, kind))
    fh.write("static const uint16_t dg_slot_%s_%s[DG_SLOT_W*DG_SLOT_H] = {\n"
             % (name, kind))
    px = img.load()
    for y in range(SLOT_H):
        row = ", ".join("0x%04X" % S.rgb565(px[x, y]) for x in range(SLOT_W))
        fh.write("  " + row + ("," if y < SLOT_H - 1 else "") + "\n")
    fh.write("};\n\n")


def main():
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEADER)
        for n in S.NAMES:
            for kind in ("outline", "filled"):
                img = S.render_slot(n, kind, SLOT_W, SLOT_H, GLASS,
                                    box_w=INK_W, box_h=INK_H,
                                    ink=S.INK, plate=S.PLATE, edge=S.PLATE_EDGE,
                                    glyph=S.GLYPH, plate_pad=3, radius=5)
                emit(fh, n, "off" if kind == "outline" else "on", img)
    print("wrote", OUT, os.path.getsize(OUT), "bytes")


if __name__ == "__main__":
    main()
