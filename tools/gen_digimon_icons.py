"""Rebuild digimon_icons.h.

  - same 8 icons, 40x40 RGB565
  - background recoloured to the UI background (0xE8E8E8) so the sprite squares vanish
  - "filled" variant rebuilt as a solid silhouette (interior holes filled), because
    the gauge and the plaster are thin-stroke drawings and looked "outlined" even
    when selected.
"""
import re, os
from PIL import Image, ImageDraw

SRC = r"<home>\digimon-passport\firmware\digimon-passport\main\core\digimon_icons.h"
DST = SRC
PREVIEW = r"<home>\digimon-passport\docs\sim-test\icons_preview.png"
BG_OLD = 0xEF5D
BG_NEW = 0xE75B   # RGB565 of the #E8E8E8 UI background
INK = 0x1082
SIZE = 40
NAMES = ["stat", "virus", "medic", "battle", "toilet", "light", "patch", "call"]

txt = open(SRC, encoding="utf-8").read()


def parse(name):
    m = re.search(r"static const uint16_t dg_icon_%s\[DG_ICON_SIZE\*DG_ICON_SIZE\] = \{(.*?)\};"
                  % name, txt, re.S)
    if not m:
        raise SystemExit("missing array: " + name)
    vals = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{4})", m.group(1))]
    assert len(vals) == SIZE * SIZE, (name, len(vals))
    return vals


def to_mask(vals):
    im = Image.new("L", (SIZE, SIZE), 0)
    px = im.load()
    for i, v in enumerate(vals):
        px[i % SIZE, i // SIZE] = 255 if v != BG_OLD else 0
    return im


def silhouette(mask):
    """Fill the interior holes of an outline drawing.

    Breadth-first flood from *every* empty border pixel: a single corner seed
    is not enough when the artwork touches the crop border and splits the
    outside into several regions (that bug produced solid blocks)."""
    from collections import deque
    w = h = SIZE
    outside = [[False] * w for _ in range(h)]
    dq = deque()
    for x in range(w):
        for y in (0, h - 1):
            if mask.getpixel((x, y)) == 0 and not outside[y][x]:
                outside[y][x] = True
                dq.append((x, y))
    for y in range(h):
        for x in (0, w - 1):
            if mask.getpixel((x, y)) == 0 and not outside[y][x]:
                outside[y][x] = True
                dq.append((x, y))
    while dq:
        x, y = dq.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < w and 0 <= ny < h and not outside[ny][nx] and mask.getpixel((nx, ny)) == 0:
                outside[ny][nx] = True
                dq.append((nx, ny))
    solid = Image.new("L", (w, h), 0)
    sp = solid.load()
    for y in range(h):
        for x in range(w):
            sp[x, y] = 255 if (mask.getpixel((x, y)) or not outside[y][x]) else 0
    return solid


def emit(fh, name, variant, vals, comment):
    fh.write("/* %s */\n" % comment)
    fh.write("static const uint16_t dg_icon_%s_%s[DG_ICON_SIZE*DG_ICON_SIZE] = {\n" % (name, variant))
    for y in range(SIZE):
        row = ", ".join("0x%04X" % v for v in vals[y * SIZE:(y + 1) * SIZE])
        fh.write("  " + row + ("," if y < SIZE - 1 else "") + "\n")
    fh.write("};\n\n")


data = []
preview = Image.new("RGB", (len(NAMES) * (SIZE + 4) + 4, SIZE * 2 + 12), (0xE8, 0xE8, 0xE8))
pp = preview.load()

for idx, name in enumerate(NAMES):
    outline = parse("%s_outline" % name)
    mask = to_mask(outline)
    solid = silhouette(mask)

    o_vals = [(BG_NEW if v == BG_OLD else v) for v in outline]
    s_vals = [INK if solid.getpixel((i % SIZE, i // SIZE)) else BG_NEW
              for i in range(SIZE * SIZE)]
    data.append((name, o_vals, s_vals))

    ox = 4 + idx * (SIZE + 4)
    for y in range(SIZE):
        for x in range(SIZE):
            # top row: selected/solid, bottom row: idle/outline
            pp[ox + x, 4 + y] = (0x10, 0x82, 0x10) if solid.getpixel((x, y)) else (0xE8, 0xE8, 0xE8)
            pp[ox + x, 8 + SIZE + y] = (0x39, 0xC7, 0x39) if mask.getpixel((x, y)) else (0xE8, 0xE8, 0xE8)

os.makedirs(os.path.dirname(PREVIEW), exist_ok=True)
preview.save(PREVIEW)

with open(DST, "w", encoding="utf-8", newline="\n") as fh:
    fh.write(
        "/* digimon_icons.h - the eight function icons of the Digital Monster face.\n"
        " * 40x40 RGB565. Background is the UI background colour, so the sprites do not\n"
        " * show up as lighter squares.\n"
        " *   outline : the silkscreened artwork (idle)\n"
        " *   filled  : solid silhouette of the same artwork (selected)\n"
        " * The silhouette matches what the real toy does: the LCD segment behind the\n"
        " * printed icon darkens the whole shape, not only the stroke.\n"
        " * Generated by tools/gen_digimon_icons.py - do not edit by hand. */\n"
        "#pragma once\n#include <stdint.h>\n\n#define DG_ICON_SIZE 40\n\n")
    for name, o_vals, s_vals in data:
        emit(fh, name, "outline", o_vals, name + " idle")
        emit(fh, name, "filled", s_vals, name + " selected")

print("wrote", DST, os.path.getsize(DST), "bytes")
print("preview", PREVIEW)
