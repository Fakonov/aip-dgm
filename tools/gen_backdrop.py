# -*- coding: utf-8 -*-
"""Regenerate dg_backdrop.h with a pale grey-green film mixed in.

The device asks for a "under the glass" look: the raw sea scene reads as a photo
pasted behind the panel.  Blending 22 % of a pale grey-green over it — the same
family as the classic olive glass — calms the colours without touching the black
dots and icons, which are drawn on top of the canvas afterwards.

Only the backdrop is generated here; the brick tile comes from gen_brick_tile.py.
"""
import io
import os
from PIL import Image

ASSETS = r'<home>\Desktop\dsh sth\aip-dgm\研究资料\multivpet_assets\shells_named'
MAIN = os.path.join('firmware', 'digimon-passport', 'main')
GW, GH = 192, 183
FILM = (150, 176, 138)      # greener film, still in the classic glass family
FILM_A = 0.30

src = Image.open(os.path.join(ASSETS, 'background_322x321_0028.png')).convert('RGB')
src = src.resize((GW, GH), Image.LANCZOS)
src = Image.blend(src, Image.new('RGB', (GW, GH), FILM), FILM_A)

words = []
for y in range(GH):
    for x in range(GW):
        r, g, b = src.getpixel((x, y))
        words.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))

L = []
L.append('/* dg_backdrop.h -- full-resolution 192x183 RGB565 backdrop for style C.')
L.append(' *')
L.append(' * Generated by tools/gen_backdrop.py from')
L.append(' * multivpet_assets/shells_named/background_322x321_0028.png (LANCZOS to 192x183)')
L.append(' * with a %.0f %% pale grey-green film (#%02X%02X%02X) blended in, so the scene reads' %
         (FILM_A * 100, FILM[0], FILM[1], FILM[2]))
L.append(' * as something UNDER the glass instead of a photo pasted behind the panel.  The')
L.append(' * dots and icons are painted on top of this and stay black.')
L.append(' *')
L.append(' * 70,272 bytes live in flash and are memcpy\'d into the glass canvas when the')
L.append(' * glass is repainted. */')
L.append('#ifndef DG_BACKDROP_H')
L.append('#define DG_BACKDROP_H')
L.append('')
L.append('#include <stdint.h>')
L.append('')
L.append('static const uint16_t dg_backdrop[%d] = {' % len(words))
for i in range(0, len(words), 16):
    L.append('    ' + ', '.join('0x%04X' % w for w in words[i:i + 16]) + ',')
L.append('};')
L.append('')
L.append('#endif /* DG_BACKDROP_H */')
io.open(os.path.join(MAIN, 'dg_backdrop.h'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')

src.save('docs/opt_backdrop_filmed.png')
print('backdrop with film written,', len(words) * 2, 'B')
